export const randomMap = () => {
  let blockInARow = 0;
  let spaceInARow = 0;
  const size = Math.floor(Math.random() * 10) + 20;
  const blockWeight = Math.floor(Math.random() * 7) + 3;
  const spaceWeight = Math.floor(Math.random() * 25) + 30;
  const map: number[][] = [];

  for (let row = 0; row < size; row++) {
    map[row] = [];
    for (let col = 0; col < size; col++) {
      let tile = 0;

      if (row === 4 && col === 3) {
        tile = 1;
      } else if (row !== 3 && col !== 4) {
        if (blockInARow > 0) {
          tile = Math.floor(Math.random() * blockWeight) > blockInARow ? 1 : 0;
        } else if (spaceInARow > 0) {
          tile = Math.floor(Math.random() * spaceWeight) > spaceInARow ? 0 : 1;
        } else {
          tile = Math.floor(Math.random() * 2);
        }
      }

      if (tile === 1) {
        blockInARow += 1;
        spaceInARow = 0;
      } else {
        spaceInARow += 1;
        blockInARow = 0;
      }
      map[row][col] = tile;
    }
  }

  return map;
};
